#!/usr/bin/env node
// Generates Dashboard/manifest.js — a list of all markdown files in ../wiki/.
// Run this whenever you add, remove, or rename wiki pages:
//   node Dashboard/build-manifest.js
const fs = require("fs");
const path = require("path");

const WIKI = path.resolve(__dirname, "..", "wiki");
const OUT = path.resolve(__dirname, "manifest.js");

function walk(dir) {
  let out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out = out.concat(walk(full));
    else if (entry.isFile() && entry.name.endsWith(".md")) {
      out.push(path.relative(WIKI, full).replace(/\\/g, "/"));
    }
  }
  return out;
}

// Skip only the reserved bookkeeping filenames at the root — everything else (including
// captures dropped in wiki/) is a real page.
const BOOKKEEPING = new Set(["index.md", "log.md", "overview.md"]);
const files = walk(WIKI).filter(f => !(f.indexOf("/") === -1 && BOOKKEEPING.has(f))).sort();
const content = `// Auto-generated by build-manifest.js. Do not edit by hand.\nwindow.AB_MANIFEST = ${JSON.stringify(files, null, 2)};\n`;
fs.writeFileSync(OUT, content);
console.log(`manifest.js: ${files.length} files`);
